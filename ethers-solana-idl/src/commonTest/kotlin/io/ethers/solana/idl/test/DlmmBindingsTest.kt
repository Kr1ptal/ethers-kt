// expected values are read from the account bytes at offsets computed independently of the generator
class DlmmBindingsTest : FunSpec({
    test("an unpacked zero-copy account decodes and re-encodes byte for byte") {
        val pair = LbClmm.LbPair.ACCOUNT.decode(LB_PAIR_DATA).unwrap()
        pair.activeId shouldBe -429
        pair.binStep shouldBe 100
        pair.tokenXMint shouldBe SolanaAddress("BbJJUTuGV2B7tJ99YeryiCBFLG39Hoc4RTzEwchtpump")
        pair.tokenYMint shouldBe SolanaAddress("So11111111111111111111111111111111111111112")
        pair.reserveX shouldBe SolanaAddress("CqrcuHpvrbKAGdHNwUrDFqyMxzLee96rHhBZkCKuo6am")
        pair.reserveY shouldBe SolanaAddress("2hjrztQiwfxZNkwEYKhesMSiR4Drbe9SHLdRb76bgTVP")
        LbClmm.LbPair.ACCOUNT.encode(pair) shouldBe LB_PAIR_DATA
    }

    test("an account of nested zero-copy structs with 128-bit integers decodes and re-encodes byte for byte") {
        val bins = LbClmm.BinArray.ACCOUNT.decode(BIN_ARRAY_DATA).unwrap()
        bins.index shouldBe -6L
        bins.lbPair shouldBe SolanaAddress("B8whnH5cSuvK9m9SR6UmkHyakD79ZirJwB79dJX1yUz8")
        bins.bins.size shouldBe 70
        bins.bins.first().price shouldBe BigInteger("282450750985822657")
        LbClmm.BinArray.ACCOUNT.encode(bins) shouldBe BIN_ARRAY_DATA
    }

    test("a zero-copy header decodes from an account with data after it") {
        val oracle = LbClmm.Oracle.ACCOUNT.decode(ORACLE_DATA).unwrap()
        oracle.idx shouldBe bigIntegerOf(53)
        oracle.activeSize shouldBe bigIntegerOf(54)
        oracle.length shouldBe bigIntegerOf(100)
    }
})
